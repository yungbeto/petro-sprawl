// Manual import: the header globe's land mask, sampled from the country outlines (public/data/countries.json,
// so run import:countries first) on a GLOBE.maskCell grid -> src/lib/globeLand.ts, and a still frame of
// it as the favicon -> public/favicon.svg
// Run: npm run import:globe

import { readFile, writeFile } from 'node:fs/promises';
import { GLOBE } from '../src/lib/config';
import { pointInPolygon } from '../src/lib/geo';
import { encodeLandRows, globeFrame, globeSvg } from '../src/lib/globe';
import type { Country } from '../src/types';

const OUT = 'src/lib/globeLand.ts';
const FAVICON = 'public/favicon.svg';
const countries = JSON.parse(await readFile('public/data/countries.json', 'utf8')) as Country[];
const cell = GLOBE.maskCell;
const width = 360 / cell;
const height = 180 / cell;

const cells: boolean[][] = [];
for (let r = 0; r < height; r++) {
  const lat = 90 - (r + 0.5) * cell;
  const row: boolean[] = [];
  for (let c = 0; c < width; c++) {
    const lon = -180 + (c + 0.5) * cell;
    row.push(countries.some((country) => pointInPolygon([lon, lat], country.geometry)));
  }
  cells.push(row);
}

const rows = encodeLandRows(cells);
const land = cells.flat().filter(Boolean).length;
await writeFile(
  OUT,
  [
    '// Generated by `npm run import:globe` from public/data/countries.json (Natural Earth). Do not edit.',
    "import type { LandMask } from './globe';",
    '',
    `export const GLOBE_LAND: LandMask = {\n  cell: ${cell},\n  rows: [\n${rows.map((r) => `    '${r}',`).join('\n')}\n  ],\n};`,
    '',
  ].join('\n'),
);
console.log(`globe: ${width}x${height} cells of ${cell}°, ${land} land (${((land / (width * height)) * 100).toFixed(1)}%) -> ${OUT}`);

const { dots, lon, fill, oceanOpacity } = GLOBE.favicon;
const frame = globeFrame({ mask: { cell, rows }, dots, lon, tilt: GLOBE.tilt });
await writeFile(FAVICON, globeSvg({ frame, dots, fill, oceanOpacity }));
console.log(`favicon: ${dots} dots across, centred on ${lon}° -> ${FAVICON}`);
